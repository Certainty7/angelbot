#!/usr/bin/env python3
"""Generate docs/AUDIT.md from the live tree (commands, modules, tables).

Read-only. Run with the repo's venv python from the project root.
"""
from __future__ import annotations

import ast
import sqlite3
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKIP = {"venv", ".git", "__pycache__", "stage", "backups"}


def py_files() -> list[Path]:
    out = []
    for p in REPO.rglob("*.py"):
        if any(part in SKIP for part in p.parts):
            continue
        out.append(p)
    return sorted(out)


def const(node) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def decorator_info(dec: ast.AST) -> dict | None:
    """Return {'kind': 'tree'|'app'|'hybrid', 'name':..., 'desc':...} for a command decorator."""
    if not isinstance(dec, ast.Call):
        return None
    fn = dec.func
    kind = None
    if isinstance(fn, ast.Attribute):
        if fn.attr == "command":
            base = fn.value
            if isinstance(base, ast.Attribute) and base.attr == "tree":
                kind = "tree"
            else:
                kind = "app"
        elif fn.attr == "hybrid_command":
            kind = "hybrid"
        elif fn.attr == "group":
            kind = "group"
        elif fn.attr in ("context_menu", "user_command", "message_command"):
            kind = "context"
    if kind is None:
        return None
    name = desc = None
    for kw in dec.keywords:
        if kw.arg == "name":
            name = const(kw.value)
        elif kw.arg == "description":
            desc = const(kw.value)
    return {"kind": kind, "name": name, "desc": desc}


def scan_commands() -> list[dict]:
    rows = []
    for path in py_files():
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        for node in ast.walk(tree):
            if not isinstance(node, (ast.AsyncFunctionDef, ast.FunctionDef)):
                continue
            for dec in node.decorator_list:
                info = decorator_info(dec)
                if info:
                    info.update(
                        func=node.name,
                        line=node.lineno,
                        file=str(path.relative_to(REPO)),
                    )
                    rows.append(info)
    return rows


def scan_imports() -> dict[str, list[str]]:
    graph: dict[str, list[str]] = {}
    for path in py_files():
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        deps = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("angel"):
                deps.add(node.module)
            elif isinstance(node, ast.Import):
                for a in node.names:
                    if a.name.startswith("angel"):
                        deps.add(a.name)
        rel = str(path.relative_to(REPO))
        if deps and rel != "bot.py":
            graph[rel] = sorted(deps)
    return graph


def scan_tables() -> list[tuple[str, int]]:
    db = REPO / "chat_history.db"
    if not db.exists():
        return []
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    tables = [
        r[0]
        for r in con.execute("select name from sqlite_master where type='table' order by name")
    ]
    con.close()
    corpus = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in py_files())
    return [(t, corpus.count(t)) for t in tables]


def main() -> None:
    cmds = scan_commands()
    kinds: dict[str, int] = {}
    for c in cmds:
        kinds[c["kind"]] = kinds.get(c["kind"], 0) + 1

    tables = scan_tables()
    imports = scan_imports()

    lines = [
        "# Audit: commands, modules, tables",
        "",
        "Generated by `tools/audit_map.py` against the live tree. Regenerate after any",
        "command change; do not hand-edit.",
        "",
        "## Command surface",
        "",
        f"Decorators found: **{len(cmds)}**: "
        + ", ".join(f"`{k}`={v}" for k, v in sorted(kinds.items())),
        "",
        "> The authoritative count is what the client registers at runtime",
        "> (`len(bot.tree.get_commands())`), not the decorator count: `@bot.tree.command` and",
        "> `@app_commands.command` can wrap the same coroutine and groups are not commands.",
        "",
        "| # | command | kind | handler | file:line | description |",
        "|---|---|---|---|---|---|",
    ]
    for i, c in enumerate(sorted(cmds, key=lambda x: (x["file"], x["line"])), 1):
        desc = (c["desc"] or "").replace("|", "\\|")
        lines.append(
            f"| {i} | `{'/' if c['kind'] != 'context' else ''}{c['name'] or c['func']}` | {c['kind']} | `{c['func']}` | "
            f"`{c['file']}:{c['line']}` | {desc} |"
        )

    lines += [
        "",
        "## Module dependency direction",
        "",
        "`bot.py` imports the `angel` package and the cogs; nothing in the package imports `bot.py`.",
        "The client reaches the package through `angel.registry`, never through a late-bound global.",
        "",
        "| module | imports |",
        "|---|---|",
    ]
    for mod, deps in sorted(imports.items()):
        lines.append(f"| `{mod}` | {', '.join(f'`{d}`' for d in deps) or '-'} |")

    unused = [t for t, n in tables if n == 0]
    lines += [
        "",
        f"## Tables ({len(tables)})",
        "",
        f"Mentioned at least once in code: {len(tables) - len(unused)}. "
        f"Never mentioned: {len(unused)}.",
        "",
        "| table | mentions in code |",
        "|---|---|",
    ]
    for t, n in tables:
        flag = "" if n else " **← unused**"
        lines.append(f"| `{t}` | {n}{flag} |")

    out = REPO / "docs" / "AUDIT.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}: commands={len(cmds)} tables={len(tables)} unused_tables={len(unused)}")
    print("kinds:", kinds)


if __name__ == "__main__":
    main()
