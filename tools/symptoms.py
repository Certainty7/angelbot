#!/usr/bin/env python3
"""Regenerate docs/SYMPTOMS.md from the systemd journal."""
from __future__ import annotations

import re
import subprocess
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
raw = subprocess.run(
    ["sudo", "-n", "journalctl", "-u", "angelbot", "--since", "30 days ago",
     "--no-pager", "-o", "cat"],
    capture_output=True, text=True,
).stdout.splitlines()

ERR = re.compile(r"ERROR|Traceback|Exception|unhandled")
VOICE = re.compile(r"voice|Voice|DAVE|davey|PyNaCl|opus|ensure_voice_connected")
TS = re.compile(r"(\d{4}-\d{2}-\d{2} \d{2}:\d{2})")


def template(line: str) -> str:
    s = re.sub(r"^\S+[ T]\S+\s*\|\s*", "", line)
    s = re.sub(r"[0-9a-f]{8,}", "<id>", s)
    s = re.sub(r"\d+", "<n>", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s[:150]


classes: dict[str, dict] = defaultdict(
    lambda: {"n": 0, "first": "", "last": "", "voice": False}
)
scanned = 0
for line in raw:
    if not ERR.search(line):
        continue
    scanned += 1
    if line.startswith(" ") and "Traceback" not in line:
        continue
    t = template(line)
    c = classes[t]
    c["n"] += 1
    m = TS.search(line)
    stamp = m.group(1) if m else "?"
    if not c["first"]:
        c["first"] = stamp
    c["last"] = stamp
    if VOICE.search(line):
        c["voice"] = True


def verdict(t: str, c: dict) -> str:
    if "auto_reply" in t or "check functions" in t:
        return "expected — permission check doing its job"
    if c["voice"] or "no attribute 'sequence'" in t:
        return "obsolete: the old voice engine was retired; re-test after the music changes"
    if "session has been invalidated" in t.lower() or "ClientConnectorError" in t:
        return "benign — reconnect noise"
    return "unknown, needs a reproduction"


rows = sorted(classes.items(), key=lambda kv: -kv[1]["n"])
lines = [
    "# Symptoms mined from the journal (30 days)",
    "",
    "Generated by `tools/symptoms.py`: error classes by template, count, first/last seen,",
    "and a verdict. Replace 'unknown' with a reproduction, a ticket, or a 'benign' proof — never a guess.",
    "",
    f"Journal lines scanned: **{scanned}** · distinct error classes: **{len(rows)}**",
    "",
    "| # | class | count | first | last | verdict |",
    "|---|---|---|---|---|---|",
]
for i, (t, c) in enumerate(rows, 1):
    lines.append(
        f"| {i} | `{t.replace('|', chr(92) + '|')}` | {c['n']} | {c['first']} | {c['last']} | {verdict(t, c)} |"
    )
unknown = sum(1 for t, c in rows if verdict(t, c).startswith("unknown"))
lines += ["", f"Unknown classes: **{unknown}**."]
out = REPO / "docs" / "SYMPTOMS.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} classes={len(rows)} unknown={unknown} scanned={scanned}")
